/** Convert synthesis sequence gates into CircuitStore-compatible gate objects */
export function sequenceToGates(sequence) {
  return sequence.map((step, i) => {
    const parts = step.qubit.split('→')
    const qubitNum = parseInt(parts[0].replace('q', ''))
    return {
      id: `synth-${i}`,
      gate: step.gate,
      qubit: qubitNum,
      targetQubit: parts[1] ? parseInt(parts[1].replace('q', '')) : null,
      step: i,
      fidelity: step.fidelity,
      aiGenerated: true,
    }
  })
}

/** Generate OpenQASM code from gate array */
export function generateQASM(gates, numQubits) {
  let code = 'OPENQASM 2.0;\n'
  code += 'include "qelib1.inc";\n\n'
  code += `qreg q[${numQubits}];\n`
  code += `creg c[${numQubits}];\n\n`

  for (const g of gates) {
    const name = g.gate.toLowerCase()
    if (name === 'cnot') {
      code += `cx q[${g.qubit}],q[${g.targetQubit}];\n`
    } else if (name === 'rx' || name === 'ry' || name === 'rz') {
      code += `${name}(pi/2) q[${g.qubit}];\n`
    } else {
      code += `${name} q[${g.qubit}];\n`
    }
  }
  return code
}

/** Generate Qiskit code from gate array */
export function generateQiskit(gates, numQubits) {
  let code = 'from qiskit import QuantumCircuit\n\n'
  code += `qc = QuantumCircuit(${numQubits})\n\n`

  for (const g of gates) {
    const name = g.gate.toLowerCase()
    if (name === 'cnot') {
      code += `qc.cx(${g.qubit}, ${g.targetQubit})\n`
    } else if (name === 'rx' || name === 'ry' || name === 'rz') {
      code += `qc.${name}(3.14159/2, ${g.qubit})\n`
    } else {
      code += `qc.${name}(${g.qubit})\n`
    }
  }

  code += '\nqc.draw()\n'
  return code
}
